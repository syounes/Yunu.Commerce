    $projects[$Name] = [ordered]@{
        Name           = $Name
        Dir            = $Dir
        Sdk            = $Sdk
        ProjectRefs    = $ProjectRefs
        Packages       = $Packages
        SolutionFolder = $SolutionFolder
        Kind           = $Kind
    }
}

