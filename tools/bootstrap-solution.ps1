<#
.SYNOPSIS
    Idempotent bootstrap script for the Yunu.Commerce solution skeleton.

.DESCRIPTION
    Creates the .NET solution structure defined in docs/architecture/06-solution-structure.md:
    - Yunu.Commerce.sln with Visual Studio Solution Folders
    - src/BuildingBlocks, src/Modules/*, src/Hosts
    - tests/Architecture, tests/Unit, tests/Integration
    - Directory.Build.props, Directory.Packages.props, global.json, .editorconfig
    - Minimal API Host, Worker Host, Architecture Tests, DI extension points,
      health-check foundation and OpenTelemetry bootstrap.

    Re-running this script overwrites generated files with deterministic content
    and re-registers projects/references, which are no-ops if already present.

.NOTES
    Generated by GitHub Copilot from the Yunu.Commerce architecture documentation,
    `.github/copilot-instructions.md`, `docs/architecture/06-solution-structure.md`,
    and the accepted ADRs.

    Does NOT create business Aggregates, Entities, Value Objects or Domain rules.
    Does NOT reference MongoDB, Kafka, Redis, Elasticsearch, Azure AI or Google AI SDKs.
#>

