function New-CsprojContent {
    param([Parameter(Mandatory)]$Def)

    $refLines = @()
    foreach ($r in $Def.ProjectRefs) {
        $target = $projects[$r]
        $targetPath = Join-Path $root "$($target.Dir)/$($target.Name).csproj"
        $fromDir = Join-Path $root $Def.Dir
        $rel = [System.IO.Path]::GetRelativePath($fromDir, $targetPath) -replace '\\', '/'
        $refLines += "    <ProjectReference Include=""$rel"" />"
    }

    $pkgLines = @()
    foreach ($p in $Def.Packages) {
        $pkgLines += "    <PackageReference Include=""$p"" />"
    }

    $extraProps = ''
    if ($Def.Kind -eq 'test') {
        $extraProps = "    <IsPackable>false</IsPackable>`n    <IsTestProject>true</IsTestProject>`n"
    }
    if ([string]::IsNullOrWhiteSpace($extraProps)) {
        $extraProps = "    <!-- shared compilation settings inherited from Directory.Build.props -->`n"
    }

    $template = @'
<Project Sdk="__SDK__">

  <PropertyGroup>
__EXTRA_PROPS__  </PropertyGroup>

  <ItemGroup>
__REFS__
  </ItemGroup>

  <ItemGroup>
__PKGS__
  </ItemGroup>

</Project>
'@

    $template.Replace('__SDK__', $Def.Sdk).
        Replace('__EXTRA_PROPS__', $extraProps).
        Replace('__REFS__', ($refLines -join "`n")).
        Replace('__PKGS__', ($pkgLines -join "`n"))
}

