function Add-ProjectDef {
    param(
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][string]$Dir,
        [string]$Sdk = 'Microsoft.NET.Sdk',
        [string[]]$ProjectRefs = @(),
        [string[]]$Packages = @(),
        [Parameter(Mandatory)][string]$SolutionFolder,
        [string]$Kind = 'lib'
